function pageLabel(pageNumber) {
  return String(pageNumber).padStart(3, '0');
}

function sourceRectFromCanvas(rect) {
  return [
    Math.round(rect.left * SOURCE_SCALE),
    Math.round(rect.top * SOURCE_SCALE),
    Math.round(rect.width * SOURCE_SCALE),
    Math.round(rect.height * SOURCE_SCALE),
  ];
}

function assignLines(lines) {
  const result = REGION_LAYOUT.map(() => []);
  const base = Math.floor(lines.length / REGION_LAYOUT.length);
  let extra = lines.length % REGION_LAYOUT.length;
  let cursor = 0;
  for (let regionIndex = 0; regionIndex < REGION_LAYOUT.length; regionIndex += 1) {
    const take = base + (extra > 0 ? 1 : 0);
    extra -= extra > 0 ? 1 : 0;
    result[regionIndex].push(...lines.slice(cursor, cursor + take));
    cursor += take;
  }
  return result;
}

function buildFocusRegions(queueId, page) {
  return REGION_LAYOUT.map((layout, index) => ({
    id: `${queueId}-p${pageLabel(page.pageNumber)}-r${String(index + 1).padStart(2, '0')}`,
    label: layout.label,
    role: layout.role,
    sourceRect: sourceRectFromCanvas(layout.canvasRect),
    canvasRect: layout.canvasRect,
  }));
}

function buildActions(queueId, page, focusRegions) {
  const grouped = assignLines(page.lines);
  const actions = [];
  let speechIndex = 1;
  for (const [index, region] of focusRegions.entries()) {
    const actionBase = `${queueId}-p${pageLabel(page.pageNumber)}-r${String(index + 1).padStart(2, '0')}`;
    actions.push({
      id: `${actionBase}-spotlight`,
      type: 'spotlight',
      elementId: region.id,
      title: region.label,
      description: `聚焦区域：${region.label}`,
      dimOpacity: 0.76,
    });
    for (const text of grouped[index]) {
      actions.push({
        id: `${actionBase}-speech-${String(speechIndex).padStart(2, '0')}`,
        type: 'speech',
        title: `讲解 ${speechIndex}`,
        text,
      });
      speechIndex += 1;
    }
  }
  return actions;
}

function validatePage(queueId, page, focusRegions, actions) {
  if (page.lines.length < 7 || page.lines.length > 10) {
    throw new Error(
      `${queueId} ${page.title}: line count ${page.lines.length} outside expected range`,
    );
  }
  const speechCount = actions.filter((action) => action.type === 'speech').length;
  const spotlightCount = actions.filter((action) => action.type === 'spotlight').length;
  if (speechCount !== page.lines.length) {
    throw new Error(`${queueId} ${page.title}: speech count mismatch`);
  }
  if (spotlightCount !== REGION_LAYOUT.length) {
    throw new Error(`${queueId} ${page.title}: spotlight count ${spotlightCount}`);
  }

  const ids = new Set(focusRegions.map((region) => region.id));
  const seen = new Set();
  const forbidden =
    /原 PDF|PDF|source-pages|source-text|queue|Week|Calculus II|Riemann|theta|pi|page\b|本页承接|if-then|iff|\bOR\b|\bNOT\b|left-total|functional|well-defined|divisor-closed|least upper bound|greatest lower bound|可以积分的量|放进积分/i;
  for (const action of actions) {
    if (seen.has(action.id))
      throw new Error(`${queueId} ${page.title}: duplicate action ${action.id}`);
    seen.add(action.id);
    if (action.type === 'spotlight' && !ids.has(action.elementId)) {
      throw new Error(`${queueId} ${page.title}: invalid target ${action.elementId}`);
    }
    if (action.type === 'speech') {
      if (!action.text || forbidden.test(action.title) || forbidden.test(action.text)) {
        throw new Error(
          `${queueId} ${page.title}: suspicious speech "${action.title}: ${action.text}"`,
        );
      }
    }
  }
}

function writeJson(filePath, value) {
  fs.mkdirSync(path.dirname(filePath), { recursive: true });
  fs.writeFileSync(filePath, `${JSON.stringify(value, null, 2)}\n`);
}

function rewriteNotebook(notebookSpec) {
  const notebookPath = path.join(ROOT, notebookSpec.queueId, 'notebook.json');
  const notebook = JSON.parse(fs.readFileSync(notebookPath, 'utf8'));
  if (notebook.pageCount !== notebookSpec.pages.length) {
    throw new Error(
      `${notebookSpec.queueId}: notebook page count ${notebook.pageCount} != spec ${notebookSpec.pages.length}`,
    );
  }

  let totalSpeech = 0;
  let totalSpotlight = 0;
  const titleByPage = new Map(notebookSpec.pages.map((page, index) => [index + 1, page.title]));

  for (const [index, pageSpec] of notebookSpec.pages.entries()) {
    const pageNumber = index + 1;
    const page = { pageNumber, ...pageSpec };
    const notebookPage = notebook.pages.find((item) => item.pageNumber === pageNumber);
    if (!notebookPage)
      throw new Error(`${notebookSpec.queueId}: missing notebook page ${pageNumber}`);

    const focusRegions = buildFocusRegions(notebookSpec.queueId, page);
    const actions = buildActions(notebookSpec.queueId, page, focusRegions);
    validatePage(notebookSpec.queueId, page, focusRegions, actions);
    totalSpeech += actions.filter((action) => action.type === 'speech').length;
    totalSpotlight += actions.filter((action) => action.type === 'spotlight').length;

    const narration = {
      schemaVersion: 1,
      notebookId: notebookSpec.queueId,
      sceneTitle: page.title,
      pageNumber,
      sourceTextPath: notebookPage.sourceTextPath,
      focusRegions,
      actions,
      qa: {
        language: 'zh-CN',
        sourceBasis: 'queue original PDF and extracted source text',
        speechCount: actions.filter((action) => action.type === 'speech').length,
        focusCount: actions.filter((action) => action.type === 'spotlight').length,
        spotlightTargetsExist: actions
          .filter((action) => action.type === 'spotlight')
          .every((action) => focusRegions.some((region) => region.id === action.elementId)),
      },
    };

    if (!DRY_RUN) writeJson(notebookPage.narrationPath, narration);
  }

  const nextNotebook = {
    ...notebook,
    pages: notebook.pages.map((page) => ({
      ...page,
      title: titleByPage.get(page.pageNumber) || page.title,
      status: {
        ...(page.status || {}),
        narration: 'ready',
      },
    })),
    status: {
      ...(notebook.status || {}),
      narration: 'ready',
    },
  };
  if (!DRY_RUN) writeJson(notebookPath, nextNotebook);
  return {
    queueId: notebookSpec.queueId,
    pages: notebookSpec.pages.length,
    totalSpeech,
    totalSpotlight,
  };
}

function main() {
  const results = NOTEBOOKS.map((notebook) => rewriteNotebook(notebook));
  for (const result of results) {
    console.log(
      `${DRY_RUN ? 'would rewrite' : 'rewrote'} ${result.queueId}: pages=${result.pages}, speech=${result.totalSpeech}, spotlight=${result.totalSpotlight}`,
    );
  }
}

main();
