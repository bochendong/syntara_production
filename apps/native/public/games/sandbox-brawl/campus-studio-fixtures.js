export const studioFixtures = [
  ...classroomFixtures,
  ...artScaleGroups.flatMap(({ id, anchor: [ax, ay], scale, fixtures }) => {
    // These cabinets stand against the aligned north wall of the studio.
    const baseY = id === 'sink' || id === 'cabinet-and-drying-rack' ? ay - 37 : ay;
    const point = ([x, y]) => [ax + (x - ax) * scale, baseY + (y - ay) * scale];
    return fixtures.map(({ kind, foot: [left, back, right, front], silhouette, holes }) =>
      fixture(kind, [...point([left, back]), ...point([right, front])],
        silhouette.map(point), holes.map((ring) => ring.map(point))));
  }),
];
