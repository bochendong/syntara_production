// Pixel coordinates on the 1586 × 992 campus painting. The footprint covers
// the furniture at floor level. The silhouette follows the visible ink above it.
function fixture(kind, foot, silhouette, holes = []) {
  return { kind, foot, silhouette, holes };
}

